def refresh_question_bank(apps, schema_editor):
    Question = apps.get_model("quiz", "Question")
    legacy_questions = list(Question.objects.filter(title__startswith="一般常識 ").order_by("id"))
    for index, (title, category, body, choices, correct_choice, correct_text) in enumerate(QUESTION_BANK):
        fields = {
            "title": title,
            "question_type": "choice",
            "category": category,
            "body": body,
            "choice_1": choices[0],
            "choice_2": choices[1],
            "choice_3": choices[2] if len(choices) == 4 else "",
            "choice_4": choices[3] if len(choices) == 4 else "",
            "correct_choice": correct_choice,
            "correct_text": correct_text,
            "explanation": "",
            "points": 10 if len(choices) == 2 else 20,
            "is_active": True,
        }
        if index < len(legacy_questions):
            Question.objects.filter(pk=legacy_questions[index].pk).update(**fields)
        else:
            Question.objects.create(**fields)


